import random
import json
from datetime import datetime

import pandas as pd
from sqlalchemy import create_engine


engine = create_engine(
    "postgresql+psycopg2://admin:admin@postgres:5432/analytics"
)


def simulate_products_cdc(nb_records=3):

    products = pd.read_sql(
        """
        SELECT *
        FROM raw.products
        """,
        engine
    )

    max_id = products["id"].max()

    categories = {
        "beauty": [
            "Face Cream",
            "Hair Serum",
            "Lip Balm",
            "Body Lotion"
        ],
        "fragrances": [
            "Night Perfume",
            "Fresh Cologne",
            "Vanilla Mist"
        ],
        "furniture": [
            "Office Desk",
            "Gaming Chair",
            "Wooden Cabinet"
        ],
        "groceries": [
            "Orange Juice",
            "Organic Honey",
            "Almond Milk",
            "Protein Bar"
        ]
    }

    rows = []

    batch_id = datetime.now().strftime("%Y%m%d%H%M%S")
    ingestion_timestamp = datetime.now()

    for i in range(nb_records):

        category = random.choice(list(categories.keys()))

        title = random.choice(categories[category])

        new_id = max_id + i + 1

        row = {
            "id": new_id,
            "title": f"{title}",
            "description": f"{title} generated by CDC simulator",
            "category": category,
            "price": round(random.uniform(5, 500), 2),
            "discountPercentage": round(random.uniform(0, 20), 2),
            "rating": round(random.uniform(3, 5), 2),
            "stock": random.randint(10, 500),
            "tags": json.dumps([category]),
            "brand": "RetailHouse",
            "sku": f"SIM-{category[:3].upper()}-{new_id}",
            "weight": random.randint(1, 10),
            "dimensions": json.dumps(
                {
                    "width": round(random.uniform(5, 30), 2),
                    "height": round(random.uniform(5, 30), 2),
                    "depth": round(random.uniform(5, 30), 2)
                }
            ),
            "warrantyInformation": "1 year warranty",
            "shippingInformation": "Ships in 3-5 business days",
            "availabilityStatus": "In Stock",
            "reviews": json.dumps([]),
            "returnPolicy": "30 days return policy",
            "minimumOrderQuantity": random.randint(1, 10),
            "meta": json.dumps(
                {
                    "createdAt": ingestion_timestamp.isoformat(),
                    "updatedAt": ingestion_timestamp.isoformat()
                }
            ),
            "images": json.dumps([]),
            "thumbnail": None,
            "batch_id": batch_id,
            "ingestion_timestamp": ingestion_timestamp,
            "source_system": "cdc_simulator"
        }

        rows.append(row)

    cdc_df = pd.DataFrame(rows)

    cdc_df.to_sql(
        "products",
        engine,
        schema="raw",
        if_exists="append",
        index=False
    )

    print(f"{len(cdc_df)} products inserted")


if __name__ == "__main__":
    simulate_products_cdc()